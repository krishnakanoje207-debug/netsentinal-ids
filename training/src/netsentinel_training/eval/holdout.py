"""Does a model recognise an attacker it has never seen?

    python -m netsentinel_training.eval.holdout --data data/processed/nf-unsw-nb15-v3 \
        --out docs/evaluation/holdout

NF-UNSW-NB15-v3 has four attacking machines, and every split contains all four. A model
tested on the same four it trained on can score well by learning *those machines* - their
addresses' neighbourhoods, for the graph model - rather than attack behaviour. This test
takes one attacker out of training and validation entirely, then tests on normal traffic
plus that attacker alone. It runs the real training functions on filtered copies of the
splits, so the numbers come from exactly the code that produced the served models.

The graph model is where this matters most: with constant node features its only way to
tell hosts apart is their neighbourhood, and with four attackers "neighbourhood of an
attacker" is close to "one of these four machines".
"""

from __future__ import annotations

import argparse
import json
import tempfile
from pathlib import Path

import polars as pl

from netsentinel_training.models import tier_a, tier_c

LABEL = tier_a.LABEL_COLUMN


def attackers(data_dir: Path) -> list[str]:
    frame = pl.read_parquet(data_dir / "train.parquet", columns=[LABEL, "src_ip"])
    return sorted(frame.filter(pl.col(LABEL) == 1).get_column("src_ip").unique().to_list())


def held_out_splits(data_dir: Path, host: str, out: Path) -> None:
    """Train and validation without the host's attacks; test is benign plus only them."""
    out.mkdir(parents=True, exist_ok=True)
    theirs = (pl.col(LABEL) == 1) & (pl.col("src_ip") == host)
    for name in ("train", "val"):
        pl.read_parquet(data_dir / f"{name}.parquet").filter(~theirs).write_parquet(out / f"{name}.parquet")
    test = pl.read_parquet(data_dir / "test.parquet")
    test.filter((pl.col(LABEL) == 0) | theirs).write_parquet(out / "test.parquet")


def summary(card: dict) -> dict:
    m = card["metrics_test"]
    return {key: m[key] for key in ("pr_auc", "recall", "precision", "false_positive_rate")}


def run(data_dir: Path, out: Path, graph_epochs: int, hosts: list[str] | None = None) -> dict:
    results: dict = {}
    for host in hosts or attackers(data_dir):
        print(f"== holding out {host}")
        # Beside the data (gitignored, on the data drive), never under docs/.
        with tempfile.TemporaryDirectory(dir=data_dir.parent) as tmp:
            split = Path(tmp) / "split"
            held_out_splits(data_dir, host, split)
            a = tier_a.train(split, Path(tmp) / "a", version=f"holdout-{host}")
            c = tier_c.train(split, Path(tmp) / "c", version=f"holdout-{host}", epochs=graph_epochs)
        results[host] = {"tier_a": summary(a), "tier_c": summary(c)}
        print(f"   Tier A PR-AUC {results[host]['tier_a']['pr_auc']:.4f} recall "
              f"{results[host]['tier_a']['recall']:.4f} | Tier C PR-AUC "
              f"{results[host]['tier_c']['pr_auc']:.4f} recall {results[host]['tier_c']['recall']:.4f}")

    out.mkdir(parents=True, exist_ok=True)
    (out / "results.json").write_text(json.dumps(results, indent=2), encoding="utf-8")
    lines = [
        "# Held-out attacker test",
        "",
        "Each row trains without one attacking machine's flows and tests on normal traffic plus "
        "that machine alone. Generated by `python -m netsentinel_training.eval.holdout`.",
        "",
        "| Held-out attacker | Tier A PR-AUC | Tier A recall | Tier A FPR | Tier C PR-AUC | Tier C recall | Tier C FPR |",
        "|---|---|---|---|---|---|---|",
    ]
    for host, r in results.items():
        a, c = r["tier_a"], r["tier_c"]
        lines.append(
            f"| {host} | {a['pr_auc']:.4f} | {a['recall']:.4f} | {a['false_positive_rate']:.4f} | "
            f"{c['pr_auc']:.4f} | {c['recall']:.4f} | {c['false_positive_rate']:.4f} |"
        )
    (out / "REPORT.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return results


def main() -> None:
    parser = argparse.ArgumentParser(description="Held-out attacker evaluation")
    parser.add_argument("--data", required=True)
    parser.add_argument("--out", default="docs/evaluation/holdout")
    parser.add_argument("--graph-epochs", type=int, default=10)
    parser.add_argument("--hosts", nargs="*", help="attackers to hold out (default: all)")
    args = parser.parse_args()
    run(Path(args.data), Path(args.out), args.graph_epochs, args.hosts)


if __name__ == "__main__":
    main()
